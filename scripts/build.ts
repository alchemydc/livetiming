// Build the SPA, embed it into the server, and compile a single binary.
//   bun scripts/build.ts            -> out/livetiming (linux-x64-baseline)
//   bun scripts/build.ts --no-compile  -> just dist/ + generated asset map (for dev)
import { readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative } from "node:path";

const root = join(import.meta.dir, "..");
const dist = join(root, "dist");
const generated = join(root, "src/server/generated/assets.ts");

function run(cmd: string[]) {
  const p = Bun.spawnSync(cmd, { cwd: root, stdout: "inherit", stderr: "inherit" });
  if (p.exitCode !== 0) throw new Error(`${cmd.join(" ")} failed (${p.exitCode})`);
}

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

run(["bunx", "vite", "build"]);

// Each dist file becomes a `with { type: "file" }` import. Under `bun run` the
// import resolves to the on-disk path; under `bun build --compile` the file is
// embedded and the import resolves to its path inside the binary.
const files = walk(dist).sort();
const lines = files.map((f, i) => `import a${i} from ${JSON.stringify(relative(join(root, "src/server/generated"), f))} with { type: "file" };`);
const entries = files.map((f, i) => `  ${JSON.stringify("/" + relative(dist, f))}: a${i},`);
mkdirSync(join(root, "src/server/generated"), { recursive: true });
writeFileSync(generated, `// Generated by scripts/build.ts. Do not edit.\n// @ts-nocheck\n${lines.join("\n")}\n\nexport const assets: Record<string, string> = {\n${entries.join("\n")}\n};\n`);
console.log(`embedded ${files.length} assets`);

if (!process.argv.includes("--no-compile")) {
  mkdirSync(join(root, "out"), { recursive: true });
  run(["bun", "build", "--compile", "--minify", "--target=bun-linux-x64-baseline", "src/server/index.ts", "--outfile", "out/livetiming"]);
}
